        private bool isSpacePressed = false;
        private void frm_sell_addtakeway_KeyDown(object sender, KeyEventArgs e)
        {
            
            string keyPressed = e.KeyCode.ToString().ToLower();

            if (keyPressed == "space")
            {
                isSpacePressed = true; // تعيين متغير للتعرف على ضغط زر الفراغ
            }
            else if (((keyPressed == "p" || keyPressed == "ب" ) && isSpacePressed)|| e.KeyCode == Keys.F2)
            {
                btn_print.PerformClick(); // تنفيذ الإجراءات عند الضغط على "ب" أو "p" بعد زر الفراغ
                isSpacePressed = false; // إعادة تعيين المتغير
            }
            else if (((keyPressed == "s" || keyPressed == "س" ) && isSpacePressed)|| e.KeyCode == Keys.F1)
            {
                btn_save.PerformClick(); // تنفيذ الإجراءات عند الضغط على "س" بعد زر الفراغ
                isSpacePressed = false; // إعادة تعيين المتغير
            }
            else if (e.KeyCode == Keys.F3)
            {
                btn_print_ch.PerformClick();
            }
            else if (e.KeyCode == Keys.F4)
            {
                btn_print_prc.PerformClick();
            }
        }

