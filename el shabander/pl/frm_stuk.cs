        private void btn_edit_Click(object sender, EventArgs e)
        {
            pl.frm_addproduct frm_supp_Add = new frm_addproduct();
            id = Convert.ToInt32(tileView2.GetFocusedRowCellValue("id"));
            var tb_service = db.tb_service.Where(x => x.id == id).FirstOrDefault();
            frm_supp_Add.edt_cat.DataSource = db.tb_cat.Select(x => x.cat_name).ToList();
            frm_supp_Add.edt_cat.Text = tb_service.name_cat.ToString();
            frm_supp_Add.edt_supp.DataSource = db.tb_main.Select(x => x.name_main).ToList();
            frm_supp_Add.edt_supp.Text = tb_service.name_main.ToString();
           
            frm_supp_Add.pic_cover.Image = bl.methods.convert_image(tb_service.pro_image);
            frm_supp_Add.edt_sales.Text =tb_service.price.ToString();
            frm_supp_Add.edt_max.Text =tb_service.cost.ToString();
            frm_supp_Add.edt_name.Text = tb_service.name_product.ToString();
           // frm_supp_Add.edt_type.Text = tb_service.type_product.ToString();
            frm_supp_Add.edt_code.Text = tb_service.code;
            
            frm_supp_Add.pictureEdit1.Image = bl.methods.convert_image(tb_service.barcode_img);



            frm_supp_Add.id = tb_service.id;
            frm_supp_Add.btn_add.Text = "تعديل";
            frm_supp_Add.Show();
        }

