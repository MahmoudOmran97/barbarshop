        private void btn_delete_Click(object sender, EventArgs e)
        {
            main user = (main)Application.OpenForms["main"];
            string casherName = user?.la_username.Text;

            var openSession = db.Sessions
                .FirstOrDefault(x => x.namecasher == casherName && x.IsClosed == true);

            if (openSession == null)
            {
                MessageBox.Show("يرجى فتح الكاش بوكس أولاً");
                return;
            }

            toast toast = new toast();
            dialog dialog = new dialog();

            try
            {
                id = Convert.ToInt32(gridView1.GetFocusedRowCellValue("id"));

                var rs = MessageBox.Show("عملية حذف", "هل انت متاكد من هذة العملية", MessageBoxButtons.YesNo);
                if (rs != DialogResult.Yes) return;

                tb_appointment = db.tb_appointment.FirstOrDefault(x => x.id == id);
                if (tb_appointment == null) return;

                if (!(tb_appointment.namecasher == casherName || tb_appointment.pay == 0))
                {
                    MessageBox.Show("لا يمكن حذف هذة الفاتورة ");
                    return;
                }

                // ✅ جلب المنتجات قبل الحذف
                var orders = db.tb_order_appointment
                    .Where(x => x.sell_id == tb_appointment.id)
                    .ToList();

                // ================== HTML + TEXT ==================
                StringBuilder html = new StringBuilder();
                StringBuilder text = new StringBuilder();

                string userName = casherName;
                string invoiceId = tb_appointment.invocie_id.ToString();
                string dateNow = DateTime.Now.ToString("yyyy/MM/dd hh:mm tt");

                html.AppendLine("<div style='direction: rtl; text-align: right; font-family: Cairo;'>");
                html.AppendLine("<h3 style='color: #e74c3c;'>🗑️ تم حذف فاتورة صالة</h3>");
                html.AppendLine("<hr>");
                html.AppendLine($"<p><strong>🧾 رقم الفاتورة:</strong> {invoiceId}</p>");
                html.AppendLine($"<p><strong>👤 المستخدم:</strong> {userName}</p>");
                html.AppendLine($"<p><strong>🕐 التاريخ:</strong> {dateNow}</p>");
                html.AppendLine("<hr>");

                html.AppendLine("<h4 style='color: #3498db;'>📦 تفاصيل الفاتورة:</h4>");
                html.AppendLine("<table border='1' style='width:100%; border-collapse:collapse; text-align:center;'>");
                html.AppendLine("<tr style='background:#f2f2f2;'>");
                html.AppendLine("<th>الصنف</th><th>الكمية</th><th>السعر</th><th>الإجمالي</th>");
                html.AppendLine("</tr>");

                text.AppendLine("🗑️ تم حذف فاتورة صالة");
                text.AppendLine($"🧾 رقم الفاتورة: {invoiceId}");
                text.AppendLine($"👤 المستخدم: {userName}");
                text.AppendLine("----------------------");

                double total = 0;

                foreach (var item in orders)
                {
                    double price = item.price_sell ?? 0;
                    double qty = item.qt_sell ?? 0;
                    double subtotal = price * qty;
                    total += subtotal;

                    html.AppendLine("<tr>");
                    html.AppendLine($"<td>{item.name_sell}</td>");
                    html.AppendLine($"<td>{qty}</td>");
                    html.AppendLine($"<td>{price}</td>");
                    html.AppendLine($"<td>{subtotal}</td>");
                    html.AppendLine("</tr>");

                    text.AppendLine($"📦 {item.name_sell} | الكمية: {qty} | السعر: {price}");
                }

                html.AppendLine("</table>");
                html.AppendLine("<hr>");
                html.AppendLine($"<h3 style='color:green;'>💰 الإجمالي: {total}</h3>");
                html.AppendLine("</div>");

                text.AppendLine("----------------------");
                text.AppendLine($"💰 الإجمالي: {total}");

                // ================== الحذف ==================
                db.Entry(tb_appointment).State = EntityState.Deleted;
                db.SaveChanges();

                var tb_chair = db.tb_chair.FirstOrDefault(x => x.name_chair == tb_appointment.sell_cus);
                if (tb_chair != null)
                {
                    tb_chair.totall_price = 0;
                    db.SaveChanges();
                }

                var tb_Safe = db.tb_safe.FirstOrDefault(x => x.safe_name == tb_appointment.safe);
                if (tb_Safe != null)
                {
                    tb_Safe.safe_count -= tb_appointment.pay;
                    db.SaveChanges();
                }

                // ================== اللوج ==================
                if (openSession != null)
                {
                    tb_OperationLog.SessionID = openSession.SessionID;
                    tb_OperationLog.OperationType = "حذف";
                    tb_OperationLog.TableName = "عملية بيع صالة";
                    tb_OperationLog.OldValue = openSession.ClosingAmount;
                    tb_OperationLog.NewValue = Convert.ToDouble(openSession.ClosingAmount - tb_appointment.pay);
                    tb_OperationLog.AmountDifference = -tb_appointment.pay;

                    db.tb_OperationLog.Add(tb_OperationLog);
                    openSession.ClosingAmount = tb_OperationLog.NewValue;

                    db.SaveChanges();
                }

                // ================== الإيميل + النوتيفيكيشن ==================
                send.SendEmailWithHtmlGridData(html.ToString());

                notfication.notfication1 = text.ToString();
                notfication.CreatedAt = DateTime.Now;

                db.Notfications.Add(notfication);
                db.SaveChanges();

                // ================== تحديث المخزون ==================
                foreach (var item in orders)
                {
                    var tb_service = db.tb_service.FirstOrDefault(x => x.name_product == item.name_sell);
                    if (tb_service == null) continue;

                    var listorder2 = db.tb_order_cat.Where(x => x.product_id == tb_service.id).ToList();

                    foreach (var order in listorder2)
                    {
                        var tb_cat = db.tb_cat.FirstOrDefault(x => x.cat_name == order.name_cat);
                        if (tb_cat != null)
                        {
                            tb_cat.qt += (Convert.ToDouble(item.qt_sell) * tb_service.price);
                            db.SaveChanges();
                        }
                    }
                }

                toast.txt_caption.Text = "تم الحذف بنجاح";
                toast.Show();

                updata_data();
            }
            catch
            {
                dialog.Width = this.Width;
                dialog.txt_capthion.Text = "لا يوجد بيع لحزفها ";
                dialog.Show();
            }
        }

        private void updata_data()
        {
            db = new DB_BarbershopEntities();
            List<tb_appointment> data = db.tb_appointment.ToList(); // جلب البيانات
            data.Reverse();
            gridControl1.DataSource = data;
            main user1 = (main)Application.OpenForms["main"];
            string casherName1 = user1?.la_username.Text;
            var openSession1 = db.Sessions.FirstOrDefault(x => x.namecasher == casherName1 && x.IsClosed == true);


            if (openSession1 != null)
            {
                var startDate = openSession1.StartTime;
                var lastDate = openSession1.EndTime ?? DateTime.Now;

                var totalSum = db.tb_appointment
                  .Where(x => x.namecasher == casherName1 &&
                              x.sell_date >= startDate &&
                              x.sell_date <= lastDate)
                  .Sum(x => x.pay);

                txtTotalSales.Text = (totalSum ?? 0).ToString();

                var totalSumb = db.tb_appointment
                                 .Where(x => x.namecasher == casherName1 &&
                                             x.sell_date >= startDate &&
                                             x.sell_date <= lastDate &&
                                             x.pay == 0)
                                 .Sum(x => x.sell_tprice);

                txtTotalSalesstop.Text = (totalSumb ?? 0).ToString();
            }
            else
            {
                MessageBox.Show("لا توجد جلسة مفتوحة لهذا الكاشير");
            }

        }

        

