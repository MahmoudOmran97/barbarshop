        private void btn_add_Click(object sender, EventArgs e)
        {
            main user = (main)Application.OpenForms["main"];
            string casherName = user?.la_username.Text;
            
            var openSession = db.Sessions
                .Where(x => x.namecasher == casherName)
                .OrderByDescending(x => x.StartTime)
                .FirstOrDefault();
            var tbsheft = db.tb_Shift.Where(x => x.SessionID == openSession.SessionID&&x.name_from==casherName).FirstOrDefault();

            if (tbsheft == null)
            {
                pl.frm_chack_hand frm_supp_Add = new frm_chack_hand();
                frm_supp_Add.id = 0;
                frm_supp_Add.btn_add.Text = "اضافة";
                frm_supp_Add.Show();
            }else
            {
                MessageBox.Show("لا يمكن اضافة وردية اخرى لى نفس الجلسة ");
            }
           
        }

