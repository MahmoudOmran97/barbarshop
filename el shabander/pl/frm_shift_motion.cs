        private void btn_edit_Click(object sender, EventArgs e)
        {
            pl.frm_chack_hand frm_supp_Add = new frm_chack_hand();
            id = Convert.ToInt32(gridView1.GetFocusedRowCellValue("id"));
            tb_Shift = db.tb_Shift.Where(x => x.id == id).FirstOrDefault();
            main user = (main)Application.OpenForms["main"];
            string casherName = user?.la_username.Text;

            // آخر جلسة للمستخدم
            var openSession = db.Sessions
               .Where(x => x.namecasher == casherName)
               .OrderByDescending(x => x.StartTime)
               .FirstOrDefault();

            // آخر شفت في نفس الجلسة لنفس الكاشير
            var tbsheft = db.tb_Shift
               .Where(x => x.SessionID == openSession.SessionID && x.name_from == casherName)
               .OrderByDescending(x => x.id)
               .FirstOrDefault();

            // الشرط: لا تعدل إلا لو هو صاحب آخر شفت في الجلسة الحالية
            if (tb_Shift.id == tbsheft?.id)
            {
                frm_supp_Add.date.Text = tb_Shift.date.ToString();
                frm_supp_Add.edt_add.Text = tb_Shift.mount.ToString();
                frm_supp_Add.stay.Text = tb_Shift.staywithcasher.ToString();
                frm_supp_Add.edt_namefrom.Text = tb_Shift.name_from;

                frm_supp_Add.edt_nameto.DataSource = db.tb_user.Select(x => x.user_name).ToList();
                frm_supp_Add.edt_nameto.Text = tb_Shift.name_to;

                frm_supp_Add.id = id;
                frm_supp_Add.btn_add.Text = "تعديل";
                frm_supp_Add.Show();
            }
            else
            {
                MessageBox.Show("لا يمكن التعديل على هذه الوردية .");
            }




        }

