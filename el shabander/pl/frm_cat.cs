        private void btn_delete_Click(object sender, EventArgs e)
        {

            toast toast = new toast();
            dialog dialog = new dialog();
            try
            {
                id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));
                var rs = MessageBox.Show("عملية حذف", "هل انت متاكد من هذة العملية", MessageBoxButtons.YesNo);
                if (rs == DialogResult.Yes)
                {
                    tb_cat = db.tb_cat.Where(x => x.id == id).FirstOrDefault();
                    if (tb_cat.qt > 0)
                    {
                        MessageBox.Show("لا يمكن حزف هذا الصنف لان يوجد كمية ");
                    }
                    else
                    {
                        db.Entry(tb_cat).State = EntityState.Deleted;
                        db.SaveChanges();

                        toast.txt_caption.Text = "تم الحذف بنجاح";
                        toast.Show();
                        updata_data();
                    }
                   
                }
               
            }
            catch
            {
                dialog.Width = this.Width;
                dialog.txt_capthion.Text = "لا يوجد صنف لحزفة";
                dialog.Show();
            }
        }

        public void updata_data()
        {
            db = new DB_BarbershopEntities();
            gridControl1.DataSource = db.tb_cat.ToList();
        }

        private void btn_edit_Click(object sender, EventArgs e)
        {
           // updata_data();
            pl.frm_cat_add frm_Cat_Add = new frm_cat_add();
            id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));
           var  tb_cat = db.tb_cat.Where(x => x.id == id).FirstOrDefault();
            frm_Cat_Add.edt_name.Text = tb_cat.cat_name.ToString();
            
            frm_Cat_Add.edt_qt.Text = tb_cat.qt.ToString();
            frm_Cat_Add.edt_type.Text = tb_cat.unit.ToString();
            frm_Cat_Add.edt_max.Text = tb_cat.max_note.ToString();
            frm_Cat_Add.pic_cover.Image = bl.methods.convert_image(tb_cat.cat_cover);
            frm_Cat_Add.id = id;
            frm_Cat_Add.btn_add.Text = "تعديل";
            frm_Cat_Add.Show();
        }

        private void btn_search_Click(object sender, EventArgs e)
        {
