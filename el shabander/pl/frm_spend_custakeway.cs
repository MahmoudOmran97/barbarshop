                        var listorder2 = db.tb_order_cat.Where(x => x.product_id == tb_product.id).ToList();
                        foreach (var order in listorder2)
                        {

                            var tb_cat = db.tb_cat.FirstOrDefault(x => x.cat_name == order.name_cat);
                            tb_cat.qt += (Convert.ToDouble(listorder[i].qt_sell) * tb_product.price);
                            db.Entry(tb_cat).State = System.Data.Entity.EntityState.Modified;
                            db.SaveChanges();
                        }
                    }
                    toast.txt_caption.Text = "تم الحذف بنجاح";
