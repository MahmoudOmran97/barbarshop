        private async void btn_delete_Click(object sender, EventArgs e)
        {
            toast toast = new toast();

            try
            {
                var rowValue = gridView1.GetFocusedRowCellValue("EmployeeId");
                if (rowValue == null)
                {
                    MessageBox.Show("يرجى اختيار صف صحيح أولاً");
                    return;
                }

                int id = Convert.ToInt32(rowValue);

                // ✅ تحقق من الحضور والمرتب
                int currentMonth = DateTime.Now.Month;
                int currentYear = DateTime.Now.Year;

                bool hasAttendanceThisMonth = db.Attendances
                    .Any(x => x.EmployeeId == id
                           && x.AttendDate.HasValue
                           && x.AttendDate.Value.Month == currentMonth
                           && x.AttendDate.Value.Year == currentYear);

                bool salaryIsPaid = db.Salaries
                    .Any(x => x.EmployeeId == id
                           && x.Month == currentMonth
                           && x.Year == currentYear
                           && x.IsPaid == true);

                if (hasAttendanceThisMonth && !salaryIsPaid)
                {
                    MessageBox.Show(
                        "لا يمكن حذف هذا الموظف!\nله حضور في الشهر الحالي ولم يستلم مرتبه بعد.",
                        "تحذير",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning);
                    return;
                }

                var rs = MessageBox.Show(
                    "هل أنت متأكد من عملية الحذف؟",
                    "تأكيد الحذف",
                    MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question);

                if (rs == DialogResult.Yes)
                {
                    var employeeToDelete = db.Employees.FirstOrDefault(x => x.EmployeeId == id);
                    if (employeeToDelete == null)
                    {
                        MessageBox.Show("لم يتم العثور على الموظف في قاعدة البيانات");
                        return;
                    }

                    // ✅ احذف من الداتابيز الأول
                    db.Employees.Remove(employeeToDelete);
                    db.SaveChanges();

                    // ✅ بعد كده احذف من جهاز Hikvision
                    try
                    {
                        var settings = db.AppSettings.FirstOrDefault(x => x.id == 1);
                        if (settings != null &&
                            !string.IsNullOrEmpty(DEVICE_IP))
                        {
                            using (var hikvision = new HikvisionService(
                               DEVICE_IP,
                                DEVICE_USER,
                                DEVICE_PASS))
                            {
                                var result = await hikvision.DeleteUserFromDeviceAsync(id);
                                if (!result.Success)
                                {
                                    // مش هنمنع الحذف لو الجهاز فيه مشكلة
                                    MessageBox.Show(
                                        $"تم الحذف من البرنامج ✅\nلكن فشل الحذف من الجهاز: {result.Message}",
                                        "تنبيه",
                                        MessageBoxButtons.OK,
                                        MessageBoxIcon.Warning);
                                }
                            }
                        }
                    }
                    catch (Exception exHik)
                    {
                        // مش هنوقف الحذف لو الجهاز مش متاح
                        MessageBox.Show(
                            $"تم الحذف من البرنامج ✅\nلكن تعذر الاتصال بالجهاز: {exHik.Message}",
                            "تنبيه",
                            MessageBoxButtons.OK,
                            MessageBoxIcon.Warning);
                    }

                    toast.txt_caption.Text = "تم الحذف بنجاح";
                    toast.Show();
                    updata_data();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show("حدث خطأ أثناء الحذف: " + ex.Message);
            }
        }

