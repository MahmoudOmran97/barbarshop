        private void btn_delete_Click(object sender, EventArgs e)
        {

            toast toast = new toast();
            dialog dialog = new dialog();
            try
            {
                id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));

                // التحقق من وجود فاتورة غير مدفوعة
                var tb_Sell_Table = db.tb_sell_takeway
                    .Where(x => x.cus_id == id && x.pay == 0)
                    .FirstOrDefault();

                if (tb_Sell_Table != null)
                {
                    MessageBox.Show("لا يمكن حذف هذا العميل لأن هناك فاتورة لم تُسدد بعد.",
                                    "تحذير",
                                    MessageBoxButtons.OK,
                                    MessageBoxIcon.Warning);
                    return;
                }

                // تأكيد عملية الحذف
                var rs = MessageBox.Show("هل أنت متأكد من حذف هذا العميل؟",
                                         "عملية حذف",
                                         MessageBoxButtons.YesNo,
                                         MessageBoxIcon.Question);
                if (rs == DialogResult.Yes)
                {
                    tb_cus = db.tb_cus.Where(x => x.id == id).FirstOrDefault();
                    if (tb_cus != null)
                    {
                        db.Entry(tb_cus).State = EntityState.Deleted;
                        db.SaveChanges();
                        main frm_supp_Add = (main)Application.OpenForms["main"];
                        string notificationMessage = $"تم حذف العميل : {tb_cus.cus_name} عن طريق : {frm_supp_Add.la_username.Text} التاريخ والوقت: {DateTime.Now:yyyy/MM/dd HH:mm:ss}.  ";
                       
                        notfication.notfication1 = notificationMessage;
                        notfication.CreatedAt = DateTime.Now;


                        db.Notfications.Add(notfication);
                        db.SaveChanges();
                        toast.txt_caption.Text = "تم الحذف بنجاح";
                        toast.Show();
                        updata_data();
                    }
                    else
                    {
                        dialog.Width = this.Width;
                        dialog.txt_capthion.Text = "العميل غير موجود.";
                        dialog.Show();
                    }
                }
            }
            catch
            {
                dialog.Width = this.Width;
                dialog.txt_capthion.Text = "لا يوجد عميل لحذفه.";
                dialog.Show();
            }

        }

