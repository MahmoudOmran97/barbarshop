        private void btn_edit_Click(object sender, EventArgs e)
        {
            main user = (main)Application.OpenForms["main"];
            string casherName = user?.la_username.Text;
            var openSession = db.Sessions.FirstOrDefault(x => x.namecasher == casherName && x.IsClosed == true);
            if (openSession == null)
            {
                MessageBox.Show("يرجى فتح الكاش بوكس أولاً");
                return;
            }
            int id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));

            // البحث عن الطاولة في قاعدة البيانات
            tb_cus = db.tb_cus.Where(x => x.id == id).FirstOrDefault();

            if (tb_cus == null)
            {
                MessageBox.Show("الطاولة غير موجودة.");
                return;
            }

            // البحث عن الفاتورة المتعلقة بالطاولة والتي لم يتم دفعها
            tb_Sell_Table = db.tb_sell_takeway.Where(x => x.cus_id == id && x.pay == 0).FirstOrDefault();

            // عرض القيم للتحقق منها
           

            // تحقق مما إذا كانت هناك فاتورة غير مدفوعة
            if (tb_Sell_Table != null && tb_Sell_Table.cus_id == id && tb_Sell_Table.pay == 0)
            {
                // عرض الفاتورة غير المدفوعة للطاولة المحددة
                pl.frm_sell_addtakeway frm_supp_Add = new frm_sell_addtakeway();
                frm_supp_Add.edt_cus.Text = tb_Sell_Table.sell_cus.ToString();
                frm_supp_Add.edt_date.Text = tb_Sell_Table.sell_date.ToString();
                frm_supp_Add.edt_pay.Text = tb_Sell_Table.pay.ToString();
                frm_supp_Add.txt_cut.Text = tb_Sell_Table.cut.ToString();
                frm_supp_Add.txt_add.Text = tb_Sell_Table.sell_add.ToString();
                frm_supp_Add.save.Text = tb_Sell_Table.safe;
                frm_supp_Add.id =tb_Sell_Table.id;
                frm_supp_Add.Show();
            }
            else
            {
                // إنشاء فاتورة جديدة للطاولة المحددة
                pl.frm_sell_addtakeway frm_supp_Add = new frm_sell_addtakeway();
                frm_supp_Add.edt_cus.Text =tb_cus.cus_name;
                frm_supp_Add.id = 0;
