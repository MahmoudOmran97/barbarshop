        private void btn_delete_Click(object sender, EventArgs e)
        {
           
            toast toast = new toast();
            dialog dialog = new dialog();
            try
            {
                id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));

                // التحقق من وجود فاتورة غير مدفوعة
                var tb_appointment = db.tb_appointment
                    .Where(x => x.cus_id == id && x.pay == 0)
                    .FirstOrDefault();

                if (tb_appointment != null)
                {
                    // رسالة تحذيرية باستخدام MessageBox
                    MessageBox.Show(
                        "لا يمكن حذف هذه المقعد لأن هناك فاتورة غير مدفوعة.",
                        "تحذير",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Warning
                    );
                    return;
                }

                // تأكيد عملية الحذف
                var rs = MessageBox.Show("عملية حذف", "هل انت متأكد من هذه العملية؟", MessageBoxButtons.YesNo);
                if (rs == DialogResult.Yes)
                {
                    tb_chair = db.tb_chair.Where(x => x.id == id).FirstOrDefault();
                    if (tb_chair != null)
                    {
                        db.Entry(tb_chair).State = EntityState.Deleted;
                        db.SaveChanges();
                        main frm_supp_Add = (main)Application.OpenForms["main"];
                        string notificationMessage = $"تم حذف المقعد : {tb_chair.name_chair} عن طريق : {frm_supp_Add.la_username.Text} التاريخ والوقت: {DateTime.Now:yyyy/MM/dd HH:mm:ss}.  ";

                        notfication.notfication1 = notificationMessage;
                        notfication.CreatedAt = DateTime.Now;
                        db.Notfications.Add(notfication);
                        db.SaveChanges();
                        toast.txt_caption.Text = "تم الحذف بنجاح";
                        toast.Show();
                        updata_data();
                    }
                    else
                    {
                        MessageBox.Show(
                            "المقعد غير موجودة.",
                            "خطأ",
                            MessageBoxButtons.OK,
                            MessageBoxIcon.Error
                        );
                    }
                }
            }
            catch
            {
                dialog.Width = this.Width;
                dialog.txt_capthion.Text = "لا يوجد عنصر لحذفه.";
                dialog.Show();
            }

        }

