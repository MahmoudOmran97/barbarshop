        private void btn_edit_Click(object sender, EventArgs e)
        {
            main user = (main)Application.OpenForms["main"];
            string casherName = user?.la_username.Text;
            var openSession = db.Sessions.FirstOrDefault(x => x.namecasher == casherName && x.IsClosed == true);
            if (openSession == null)
            {
                MessageBox.Show("يرجى فتح الكاش بوكس أولاً");
                return;
            }
            int id = Convert.ToInt32(tileView1.GetFocusedRowCellValue("id"));

            // البحث عن المقعد في قاعدة البيانات
            tb_chair = db.tb_chair.Where(x => x.id == id).FirstOrDefault();

            if (tb_chair == null)
            {
                MessageBox.Show("المقعد غير موجودة.");
                return;
            }

            // البحث عن الفاتورة المتعلقة بالمقعد والتي لم يتم دفعها
            tb_appointment = db.tb_appointment.Where(x => x.cus_id == id && x.pay == 0).FirstOrDefault();

            // عرض القيم للتحقق منها
           

            // تحقق مما إذا كانت هناك فاتورة غير مدفوعة
            if (tb_appointment != null && tb_appointment.cus_id == id && tb_appointment.pay == 0)
            {
                // عرض الفاتورة غير المدفوعة للمقعد المحددة
                pl.frm_sell_add frm_supp_Add = new frm_sell_add();
                frm_supp_Add.edt_cus.Text = tb_appointment.sell_cus.ToString();
                frm_supp_Add.edt_date.Text = tb_appointment.sell_date.ToString();
                frm_supp_Add.edt_pay.Text = tb_appointment.pay.ToString();
                frm_supp_Add.txt_cut.Text = tb_appointment.cut.ToString();
                frm_supp_Add.txt_add.Text = tb_appointment.sell_add.ToString();
                frm_supp_Add.save.Text = tb_appointment.safe;
                frm_supp_Add.id =tb_appointment.id;
                frm_supp_Add.Show();
            }
            else
            {
                // إنشاء فاتورة جديدة للمقعد المحددة
                pl.frm_sell_add frm_supp_Add = new frm_sell_add();
                frm_supp_Add.edt_cus.Text = tb_chair.name_chair;
                frm_supp_Add.id = 0;
